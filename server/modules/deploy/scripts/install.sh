#!/usr/bin/env sh
# install.sh - install the Breaker stack from a release tag.
#
# Usage: install.sh --remote REMOTE [--tag TAG] [--env-file PATH]
#                 [--compose FILE] [--staging DIR] [--backup-out DIR]
#                 [--no-backup] [--keep N] [--timeout SECONDS]
#
# --keep N (default 5) is forwarded to the backup call: the N most recent
# stamp directories the backup root keeps. A non-integer or <= 0 value is a
# usage error (exit 2).
#
# Steps, in order: preflight part 1, pull, env file, service key, preflight
# part 2, host build, image build, backup and schema record (only when a
# database file already exists in the volumes; an unresolvable volume is a
# hard failure, and --no-backup skips the backup alone), swap, health,
# vpn-bind. One line per step goes to stdout; a secret VALUE (any NAME
# containing KEY/TOKEN/PASSWORD/SECRET, or the key file content) and
# BREAKER_WHISPER_FORWARDER_URL are never printed, logged, or placed in an
# argument list; only a NAME or a verdict word. The bind address, the ports
# and the three health URLs MAY print. The service key value is generated by
# python3 into a 0600 temp file in the key directory and moved onto its final
# path; it is read back from that file, never passed as an argument.
#
# Exit: 0 ok; 1 a step failed; 2 usage; 3 no release tag.
#
# POSIX sh, no bashisms. BREAKER_KEY_HOST_DEFAULT is a test seam for the
# default key file path; unset, the default is /etc/breaker/sync-api-service-key.

set -u

SCRIPT_DIR=$(CDPATH='' cd "$(dirname "$0")" && pwd)
# the sourced file is a sibling found through SCRIPT_DIR; `shellcheck -s sh`
# cannot resolve a dynamic path, so the "not following" note is a false positive.
# shellcheck disable=SC1091
. "$SCRIPT_DIR/deploy-common.sh"

REMOTE=""
TAG=""
TAG_GIVEN=0
ENV_FILE="/etc/breaker/stack.env"
COMPOSE_FILE=""
STAGING=""
BACKUP_OUT=/var/backups/breaker
NO_BACKUP=0
KEEP=5
TIMEOUT=5
KEY_HOST_DEFAULT=${BREAKER_KEY_HOST_DEFAULT:-/etc/breaker/sync-api-service-key}

usage_error() {
    echo "install.sh: $1" >&2
    exit 2
}

# install_fail MSG - deploy_fail always returns 1; swallow that so a caller can
# choose its own exit code under set -e (the message still goes to stderr).
install_fail() {
    deploy_fail "$@" || true
}

# install_env_rewrite PATH - rewrite the env file's two service-key lines.
# PATH is both the host path to write and the key file to read the whisper
# value from; the value itself is never an argument, it flows through awk.
install_env_rewrite() {
    _ier_path=$1
    _ier_tmp="${ENV_FILE}.tmp.$$"
    awk -v host="$_ier_path" -v keyfile="$_ier_path" '
        BEGIN {
            _ier_key = ""
            while ((getline _ier_line < keyfile) > 0) { _ier_key = _ier_line; break }
            close(keyfile)
        }
        {
            if ($0 ~ /^BREAKER_SYNC_API_SERVICE_KEY_HOST=/) {
                print "BREAKER_SYNC_API_SERVICE_KEY_HOST=" host
                _ier_seen_host = 1
            } else if ($0 ~ /^BREAKER_WHISPER_SYNC_API_SERVICE_KEY=/) {
                print "BREAKER_WHISPER_SYNC_API_SERVICE_KEY=" _ier_key
                _ier_seen_key = 1
            } else {
                print
            }
        }
        END {
            if (!_ier_seen_host) print "BREAKER_SYNC_API_SERVICE_KEY_HOST=" host
            if (!_ier_seen_key) print "BREAKER_WHISPER_SYNC_API_SERVICE_KEY=" _ier_key
        }
    ' "$ENV_FILE" > "$_ier_tmp" || {
        rm -f "$_ier_tmp"
        install_fail "cannot rewrite the env file"
        return 1
    }
    chmod 600 "$_ier_tmp" || {
        rm -f "$_ier_tmp"
        install_fail "cannot set the env file mode"
        return 1
    }
    mv "$_ier_tmp" "$ENV_FILE" || {
        rm -f "$_ier_tmp"
        install_fail "cannot replace the env file"
        return 1
    }
}

while [ $# -gt 0 ]; do
    case "$1" in
        --remote)
            [ $# -ge 2 ] || usage_error "--remote requires a value"
            REMOTE=$2
            shift 2
            ;;
        --tag)
            [ $# -ge 2 ] || usage_error "--tag requires a value"
            TAG=$2
            TAG_GIVEN=1
            shift 2
            ;;
        --env-file)
            [ $# -ge 2 ] || usage_error "--env-file requires a value"
            ENV_FILE=$2
            shift 2
            ;;
        --compose)
            [ $# -ge 2 ] || usage_error "--compose requires a value"
            COMPOSE_FILE=$2
            shift 2
            ;;
        --staging)
            [ $# -ge 2 ] || usage_error "--staging requires a value"
            STAGING=$2
            shift 2
            ;;
        --backup-out)
            [ $# -ge 2 ] || usage_error "--backup-out requires a value"
            BACKUP_OUT=$2
            shift 2
            ;;
        --no-backup)
            NO_BACKUP=1
            shift
            ;;
        --keep)
            [ $# -ge 2 ] || usage_error "--keep requires a value"
            KEEP=$2
            shift 2
            ;;
        --timeout)
            [ $# -ge 2 ] || usage_error "--timeout requires a value"
            TIMEOUT=$2
            shift 2
            ;;
        --*)
            usage_error "unknown option $1"
            ;;
        *)
            usage_error "unexpected argument $1"
            ;;
    esac
done

[ -n "$REMOTE" ] || usage_error "--remote is required"

case "$KEEP" in
    ''|*[!0-9]*)
        usage_error "--keep must be a positive integer"
        ;;
esac
[ "$KEEP" -ge 1 ] || usage_error "--keep must be a positive integer"

if [ -z "$STAGING" ]; then
    STAGING=/var/tmp/breaker-deploy/$(date -u +%Y%m%dT%H%M%SZ)-$$
fi
if [ -z "$COMPOSE_FILE" ]; then
    COMPOSE_FILE="$STAGING/server/modules/deploy/docker-compose.yml"
fi
STAGING_PARENT=$(dirname "$STAGING")
SCHEMA_FILE="$STAGING_PARENT/update-schema-before.$$"
# The record is a TEMP file in the staging parent: remove it on EVERY exit
# path, including a failed run, so not one file is left behind per run.
trap 'rm -f "$SCHEMA_FILE"' EXIT
EXAMPLE_FILE="$STAGING/server/modules/deploy/.env.example"

# ---- 1. the tag -----------------------------------------------------------
if [ "$TAG_GIVEN" -eq 0 ]; then
    refs=$(git -c protocol.ext.allow=never ls-remote --tags -- "$REMOTE" 2>/dev/null) || {
        install_fail "cannot list tags from --remote"
        exit 1
    }
    TAG=$(printf '%s\n' "$refs" | cut -f2 | sed 's|^refs/tags/||; s|\^{}$||' | sort -u |
        sh "$SCRIPT_DIR/release-tags.sh" latest) || {
        install_fail "no release tag on the remote"
        exit 3
    }
fi
export BREAKER_IMAGE_TAG="$TAG"
export TIMEOUT

# ---- 2. preflight part 1 (before the pull) --------------------------------
printf 'install: preflight\n'
for tool in git docker curl python3; do
    command -v "$tool" >/dev/null 2>&1 || {
        install_fail "required tool missing: $tool"
        exit 1
    }
done
if [ ! -d "$STAGING_PARENT" ]; then
    mkdir -p "$STAGING_PARENT" || {
        install_fail "cannot create STAGING_PARENT"
        exit 1
    }
fi
if ! deploy_dir_writable "$STAGING_PARENT"; then
    install_fail "STAGING_PARENT is not a writable directory"
    exit 1
fi
compose_version=$(docker compose version 2>/dev/null) || {
    install_fail "docker compose version is not available (compose v2 is required)"
    exit 1
}
# The rule lives in deploy-common.sh: the MAJOR is compared numerically, so
# v2 and v5 both pass while docker-compose v1 is refused. A failing docker
# stays the caller's own hard failure above, keeping the two diagnostics
# ("not available" versus "not v2") distinct.
if ! deploy_compose_version_ok "$compose_version"; then
    install_fail "docker compose version is not v2"
    exit 1
fi
if ! docker buildx version >/dev/null 2>&1; then
    echo "deploy: NOTE docker buildx is not available"
fi
# (d) the root/sudo fact: the key step's chown 10001 needs root. One line.
if [ "$(id -u 2>/dev/null)" = "0" ]; then
    echo "install: root: yes"
elif command -v sudo >/dev/null 2>&1; then
    echo "install: root: no, sudo: yes"
else
    echo "install: root: no, sudo: no"
fi
# (e) the early bind check, only when the env file already exists and has a
#     non-empty BREAKER_BIND_ADDR. A fresh install's env file is created from
#     the pulled .env.example, so the pull must precede the env step; this
#     refuses a bad bind BEFORE the pull, and preflight part 2 checks it again.
if [ -f "$ENV_FILE" ]; then
    early_bind=$(deploy_env_value BREAKER_BIND_ADDR)
    if [ -n "$early_bind" ]; then
        early_class=$(deploy_addr_class "$early_bind") || true
        case "$early_class" in
            private|loopback) ;;
            *)
                install_fail "BREAKER_BIND_ADDR is ${early_class:-empty}"
                exit 1
                ;;
        esac
    fi
fi

# ---- 3. pull --------------------------------------------------------------
# Force the normal umask for the checkout and the builds: a root shell with
# umask 077 would check out 0600 files and build 0600 outputs, and the images
# COPY those trees (web-fe's nginx.conf.template and docker-entrypoint.sh are
# read by uid 10001). The key/env section below tightens to 077 for its own
# files and restores 022 afterwards.
umask 022
printf 'install: pull\n'
pull_rc=0
if [ "$TAG_GIVEN" -eq 1 ]; then
    "$SCRIPT_DIR/git-pull.sh" --remote "$REMOTE" --dest "$STAGING" --tag "$TAG" || pull_rc=$?
else
    "$SCRIPT_DIR/git-pull.sh" --remote "$REMOTE" --dest "$STAGING" || pull_rc=$?
fi
if [ "$pull_rc" -ne 0 ]; then
    install_fail "pull failed"
    exit "$pull_rc"
fi

# ---- 4. the env file ------------------------------------------------------
# The env file and the service key are created under a restrictive umask: the
# key value passes through a temp file, and the env rewrite writes a temp file
# beside ENV_FILE before chmod 600. The checkout and the builds run under the
# forced 022 from step 3, so the files the images COPY keep their normal modes.
umask 077
printf 'install: env\n'
env_dir=$(dirname "$ENV_FILE")
if [ ! -d "$env_dir" ]; then
    mkdir -p "$env_dir" || {
        install_fail "cannot create the env directory"
        exit 1
    }
fi
chmod 700 "$env_dir" || {
    install_fail "cannot set the env directory mode"
    exit 1
}
if [ ! -f "$ENV_FILE" ]; then
    [ -f "$EXAMPLE_FILE" ] || {
        install_fail "the env example is missing from the checkout"
        exit 1
    }
    cp "$EXAMPLE_FILE" "$ENV_FILE" || {
        install_fail "cannot create the env file"
        exit 1
    }
    chmod 600 "$ENV_FILE" || {
        install_fail "cannot set the env file mode"
        exit 1
    }
else
    if ! deploy_env_mode_ok "$ENV_FILE"; then
        install_fail "ENV_FILE mode is not 0600"
        exit 1
    fi
fi

# ---- 5. the service key ---------------------------------------------------
printf 'install: key\n'
key_host=$(deploy_env_value BREAKER_SYNC_API_SERVICE_KEY_HOST)
need_env_rewrite=0
if [ -z "$key_host" ]; then
    key_host=$KEY_HOST_DEFAULT
    need_env_rewrite=1
fi
key_dir=$(dirname "$key_host")
if [ ! -d "$key_dir" ]; then
    mkdir -p "$key_dir" || {
        install_fail "cannot create the key directory"
        exit 1
    }
fi
chmod 700 "$key_dir" || {
    install_fail "cannot set the key directory mode"
    exit 1
}

if [ ! -f "$key_host" ]; then
    # Generate into a 0600 temp file in the same 0700 directory, validate the
    # length, then mv it onto the final path. The value is never an argument;
    # python3 writes it to the file. A failure removes the temp file and leaves
    # NO final key file, so a later run cannot refuse an empty key forever.
    key_tmp="$key_dir/.sync-api-service-key.$$.tmp"
    (umask 077; : > "$key_tmp") || {
        install_fail "cannot create the key temp file"
        exit 1
    }
    chmod 600 "$key_tmp" || {
        rm -f "$key_tmp"
        install_fail "cannot set the key temp file mode"
        exit 1
    }
    if ! python3 - "$key_tmp" <<'PY'
import secrets
import sys
with open(sys.argv[1], "w", encoding="utf-8") as handle:
    handle.write(secrets.token_urlsafe(32))
PY
    then
        rm -f "$key_tmp"
        install_fail "cannot generate the service key"
        exit 1
    fi
    key_len=$(wc -c < "$key_tmp" | tr -d ' ')
    case "$key_len" in
        ''|*[!0-9]*)
            rm -f "$key_tmp"
            install_fail "cannot generate the service key"
            exit 1
            ;;
    esac
    [ "$key_len" -eq 43 ] || {
        rm -f "$key_tmp"
        install_fail "cannot generate the service key"
        exit 1
    }
    mv "$key_tmp" "$key_host" || {
        rm -f "$key_tmp"
        install_fail "cannot install the service key file"
        exit 1
    }
    chmod 600 "$key_host" || {
        install_fail "cannot set the key file mode"
        exit 1
    }
    # The env lines are written BEFORE the chown attempt: a chown failure must
    # not leave an empty whisper line that the next run refuses forever.
    install_env_rewrite "$key_host" || exit 1
    need_env_rewrite=0
    if ! chown 10001 "$key_host" 2>/dev/null; then
        install_fail "the key file must be owned by uid 10001; not root: run 'chown 10001 $key_host'"
        exit 1
    fi
else
    key_mode=$(stat -c '%a' "$key_host" 2>/dev/null)
    [ "$key_mode" = "600" ] || {
        install_fail "the key file mode is not 0600"
        exit 1
    }
    key_len=$(wc -c < "$key_host" | tr -d ' ')
    case "$key_len" in
        ''|*[!0-9]*)
            install_fail "the key file is not 43 characters"
            exit 1
            ;;
    esac
    [ "$key_len" -eq 43 ] || [ "$key_len" -eq 44 ] || {
        install_fail "the key file is not 43 characters"
        exit 1
    }
    key_owner=$(stat -c '%u' "$key_host" 2>/dev/null)
    [ "$key_owner" = "10001" ] || {
        install_fail "the key file must be owned by uid 10001: $key_host"
        exit 1
    }
    env_key=$(deploy_env_value BREAKER_WHISPER_SYNC_API_SERVICE_KEY)
    file_key=$(cat "$key_host")
    [ "${#file_key}" -eq 43 ] || {
        install_fail "the key file is not 43 characters"
        exit 1
    }
    if [ -z "$env_key" ]; then
        # An empty whisper line means "fill it from the key file"; a
        # non-empty value that differs still refuses.
        install_env_rewrite "$key_host" || exit 1
        need_env_rewrite=0
    elif [ "$file_key" != "$env_key" ]; then
        install_fail "the key file does not match BREAKER_WHISPER_SYNC_API_SERVICE_KEY"
        exit 1
    fi
fi

if [ "$need_env_rewrite" -eq 1 ]; then
    install_env_rewrite "$key_host" || exit 1
fi

# The key/env section is over: back to the forced 022 for the builds, never
# the caller's umask (a 077 caller would build 0600 outputs).
umask 022

# ---- 4b. preflight part 2 (the env file is complete now) ------------------
if ! deploy_preflight; then
    exit 1
fi

# ---- 6. host build --------------------------------------------------------
printf 'install: build\n'
# gradlew is checked HERE, in the pulled checkout, not in preflight: it is a
# property of the tag, not of the host.
if [ ! -x "$STAGING/gradlew" ]; then
    install_fail "gradlew is missing or not executable in the checkout: $STAGING/gradlew"
    exit 1
fi
if ! (cd "$STAGING" && ./gradlew :server:modules:sync-api:installDist :server:modules:whisper-server:installDist :server:modules:web-fe:assemble); then
    install_fail "host build failed"
    exit 1
fi

# ---- 7. image build -------------------------------------------------------
printf 'install: image\n'
if ! docker compose --env-file "$ENV_FILE" -p breaker -f "$COMPOSE_FILE" build --no-cache; then
    install_fail "image build failed"
    exit 1
fi

# ---- 8. backup and schema record -------------------------------------------
# Only a reinstall over existing data takes a backup. The host paths come
# from deploy_db_paths: a volume NOT listed there is ABSENT (first install,
# or removed) and prints an EMPTY line, which is not an error; a LISTED
# volume whose inspect fails or answers no mountpoint is UNRESOLVABLE and
# is a HARD FAILURE, never "no data". The --db list is built from the
# NON-EMPTY paths only, so an absent volume never becomes an empty --db
# (backup-data.py would fall back to its environment variable and could
# back up the wrong file). The backup call is --out plus one --sync-db /
# --whisper-db per NON-EMPTY path, for the same reason: --db is not an --out
# flag at all, and an empty --sync-db "" would fall back to the environment.
# With no path at all there is nothing to probe:
# --has-data is not called (it exits 2 on an empty list) and the backup and
# the schema record are both skipped. --has-data exit 3 means no database
# file exists: the backup and the schema record are both skipped.
# --no-backup is an explicit opt-out of the backup alone; the schema record
# still runs.
printf 'install: data\n'
DATA_PRESENT=0
_idb_raw=$(deploy_db_paths) || exit 1
SYNC_DB=$(printf '%s\n' "$_idb_raw" | sed -n '1p')
WHISPER_DB=$(printf '%s\n' "$_idb_raw" | sed -n '2p')
# The --db argv is positional parameters built from individually QUOTED
# values, never a concatenated string word-split at the call site: a host
# path containing a space must survive as ONE argument. An empty slot
# contributes no flag at all.
set --
[ -n "$SYNC_DB" ] && set -- "$@" --db "$SYNC_DB"
[ -n "$WHISPER_DB" ] && set -- "$@" --db "$WHISPER_DB"
if [ "$#" -eq 0 ]; then
    echo "install: first install, nothing to back up"
else
    has_rc=0
    python3 "$SCRIPT_DIR/backup-data.py" --has-data "$@" || has_rc=$?
    case "$has_rc" in
        0) DATA_PRESENT=1 ;;
        3) echo "install: first install, nothing to back up" ;;
        *)
            install_fail "cannot tell whether a database file exists (exit $has_rc)"
            exit 1
            ;;
    esac
fi

if [ "$DATA_PRESENT" -eq 1 ]; then
    if [ "$NO_BACKUP" -eq 1 ]; then
        echo "install: backup skipped (--no-backup)"
    else
        echo "install: backup the data"
        # --out takes --sync-db/--whisper-db, never --db (--db belongs to
        # --has-data and --record-schema). A volume that is absent contributes
        # NO flag at all: an empty --sync-db "" would make the tool fall back to
        # its environment variable and could back up the wrong file.
        # The argv is positional parameters built from individually QUOTED
        # values, never a concatenated string word-split at the call site: a
        # host path containing a space must survive as ONE argument. The
        # script's own positional parameters are free to clobber here -- the
        # --has-data probe above has already consumed them and nothing later
        # reads $@/$# (verified: they appear only in the arg loop, that probe
        # and the install_fail/install_env_rewrite function bodies, which are
        # function-local).
        set --
        [ -n "$SYNC_DB" ] && set -- "$@" --sync-db "$SYNC_DB"
        [ -n "$WHISPER_DB" ] && set -- "$@" --whisper-db "$WHISPER_DB"
        set -- "$@" --keep "$KEEP"
        if ! python3 "$SCRIPT_DIR/backup-data.py" --out "$BACKUP_OUT" "$@"; then
            install_fail "backup failed; the stack was not changed"
            exit 1
        fi
    fi
    echo "install: schema record"
    # deploy_record_schema takes the raw paths (it builds the --db flags
    # itself), so the same NON-EMPTY list is passed without the flags. Its
    # argv is positional parameters built from individually QUOTED values,
    # never a concatenated string word-split at the call site: a host path
    # containing a space must survive as ONE argument. DATA_PRESENT=1
    # guarantees at least one NON-EMPTY slot, which is what
    # deploy_record_schema requires.
    set --
    [ -n "$SYNC_DB" ] && set -- "$@" "$SYNC_DB"
    [ -n "$WHISPER_DB" ] && set -- "$@" "$WHISPER_DB"
    if ! deploy_record_schema "$SCHEMA_FILE" "$@"; then
        install_fail "schema record failed; the stack was not changed"
        exit 1
    fi
fi

# ---- 9. swap --------------------------------------------------------------
printf 'install: swap\n'
if ! docker compose --env-file "$ENV_FILE" -p breaker -f "$COMPOSE_FILE" up -d; then
    install_fail "swap failed"
    exit 1
fi

# ---- 10. health -----------------------------------------------------------
printf 'install: health\n'
bind=$(deploy_env_value BREAKER_BIND_ADDR)
sync_port=$(deploy_env_value BREAKER_SYNC_API_PORT)
whisper_port=$(deploy_env_value BREAKER_WHISPER_PORT)
web_port=$(deploy_env_value BREAKER_WEB_FE_PORT)
health_urls=$(deploy_health_urls "$bind" "$sync_port" "$whisper_port" "$web_port") || {
    install_fail "cannot build the health URLs"
    exit 1
}
# The three URLs are caller-built literals; split them back into words.
# shellcheck disable=SC2086
if ! deploy_check_health $health_urls; then
    install_fail "health check failed"
    exit 1
fi

# ---- 11. vpn-bind (fail closed) -------------------------------------------
printf 'install: vpn-bind\n'
vpn_rc=0
vpn_out=$("$DEPLOY_SCRIPTS_DIR/vpn-bind.sh" --vpn-addr "$bind" --ports "$sync_port,$whisper_port,$web_port" 2>&1) || vpn_rc=$?
if [ "$vpn_rc" -ne 0 ]; then
    exposed=$(printf '%s\n' "$vpn_out" | awk '$2 == "exposed" { printf "%s ", $1 }')
    if [ -n "$exposed" ]; then
        install_fail "port exposed: $exposed"
        docker compose --env-file "$ENV_FILE" -p breaker -f "$COMPOSE_FILE" stop
        exit 1
    fi
    install_fail "vpn-bind failed"
    exit 1
fi

printf 'install: ok\n'
