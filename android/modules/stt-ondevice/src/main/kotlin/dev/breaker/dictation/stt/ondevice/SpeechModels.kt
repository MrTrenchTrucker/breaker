package dev.breaker.dictation.stt.ondevice

import dev.breaker.shared.models.ModelEntry
import dev.breaker.shared.models.ModelKind
import dev.breaker.shared.models.ModelRegistry
import java.io.File

/**
 * Where this module learns what a speech model is: from its registry entry, never from its id.
 *
 * A model is data. An entry the registry marks as a supported (kind, model type) pair and that carries its four
 * file names and its extraction limits is a speech model this module can unpack and run; any other entry, and any
 * id the registry does not know, is not. No model id is written in this module. This code is written but not
 * compiled or run, and the registry's `isSupported` name is the one generated by the registry tool.
 */
internal object SpeechModels {

    /**
     * The entry for [modelId] when it is a usable speech model (and of kind [kind] when one is given), else null.
     * [lookup] is the registry; the real one is the default, a test passes its own.
     */
    fun usable(
        modelId: String,
        lookup: (String) -> ModelEntry? = ModelRegistry::byId,
        kind: ModelKind? = null,
    ): ModelEntry? {
        val entry = lookup(modelId) ?: return null
        if (!entry.isSupported || entry.files == null || entry.limits == null) return null
        return if (kind == null || entry.kind == kind) entry else null
    }

    /**
     * The four files of [entry] inside [directory], found by the names the entry gives, with the entry's model
     * type. Returns null when [entry] has no file names, or a named file is missing, empty or not a regular file.
     */
    fun locate(directory: File, entry: ModelEntry): TransducerFiles? {
        val names = entry.files ?: return null
        val files = TransducerFiles(
            encoder = File(directory, names.encoder),
            decoder = File(directory, names.decoder),
            joiner = File(directory, names.joiner),
            tokens = File(directory, names.tokens),
            modelType = entry.modelType.orEmpty(),
        )
        val all = listOf(files.encoder, files.decoder, files.joiner, files.tokens)
        return if (all.all { it.isFile && it.length() > 0L }) files else null
    }
}
