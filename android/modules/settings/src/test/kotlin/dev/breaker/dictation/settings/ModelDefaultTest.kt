package dev.breaker.dictation.settings

import dev.breaker.dictation.core.model.AppSettings
import dev.breaker.shared.models.ModelRegistry
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The core default model id and the registry default are the same one.
 *
 * The core module cannot see the registry, so its `modelSize` default is a
 * literal. This module sees both, so the literal is pinned here against the
 * registry entry whose `isDefault` is true. Every expected value is asked of
 * the registry, never re-typed. This test is written against the registry's
 * default flag and is not compiled or run here (the flag is generated by the
 * registry work in the same round; not built until that lands).
 */
class ModelDefaultTest {

    /** Exactly one entry carries the default flag. */
    @Test
    fun `exactly one registry entry is the default`() {
        val defaults = ModelRegistry.ALL.filter { it.isDefault }

        assertEquals("the default entries: ${defaults.map { it.id }}", 1, defaults.size)
    }

    /** The default is an entry the app offers. */
    @Test
    fun `the default entry is offered`() {
        val default = ModelRegistry.ALL.single { it.isDefault }

        assertTrue("the default ${default.id} must be offered", default.offered)
    }

    /** The core literal names the registry default. */
    @Test
    fun `a fresh AppSettings names the registry default model`() {
        val default = ModelRegistry.ALL.single { it.isDefault }

        assertEquals("the core modelSize default", default.id, AppSettings().modelSize)
    }
}
