"""tools/model_registry_render.py - the Kotlin text of the model registry, split
out of tools/gen_model_registry.py (ADR-016, ADR-050).

render_kotlin turns converted entries into the committed
ModelRegistry.kt, deterministically: the same entries always give the same
bytes. The generated names other code reads:

* `ModelFiles(encoder, decoder, joiner, tokens)` and `ModelLimits(maxEntryBytes,
  maxWrittenBytes, maxStreamBytes, maxEntries, maxDepth)`;
* the `ModelEntry` fields modelType, files, limits, language, isDefault, notice;
* `ModelRegistry.SUPPORTED_TYPES`: Set<Pair<ModelKind, String>>, the pairs of
  tools/model_types.py;
* `ModelEntry.isSupported`: true when the entry has modelType, files, limits and
  language and its (kind, modelType) pair is in SUPPORTED_TYPES.

The Kotlin is written by the generator and compiled by nobody in this tree.
"""
import re

import model_registry_fields as mrf
import model_types

HEADER = [
    "// Generated by tools/gen_model_registry.py from models.yaml —",
    "// do not edit by hand. Edit models.yaml and rerun the generator.",
    "// (ADR-016: the app reads these constants; nothing parses YAML at runtime.)",
    "package dev.breaker.shared.models",
    "",
    "enum class ModelFamily {",
    "    SHERPA_ONNX,",
    "    WHISPER,",
    "}",
    "",
    "enum class ModelKind {",
    "    STREAMING,",
    "    OFFLINE,",
    "}",
    "",
    "/** The four file names inside an archive, flat under its single top folder. */",
    "data class ModelFiles(",
    "    val encoder: String,",
    "    val decoder: String,",
    "    val joiner: String,",
    "    val tokens: String,",
    ")",
    "",
    "/** The bounds one unpack of the archive works within. */",
    "data class ModelLimits(",
    "    val maxEntryBytes: Long,",
    "    val maxWrittenBytes: Long,",
    "    val maxStreamBytes: Long,",
    "    val maxEntries: Int,",
    "    val maxDepth: Int,",
    ")",
    "",
    "data class ModelEntry(",
    "    val id: String,",
    "    val family: ModelFamily,",
    "    val url: String,",
    "    val sha256: String,",
    "    val sizeMb: Int,",
    "    val licence: String,",
    "    val hosted: Boolean,",
    '    val archiveName: String = "",',
    "    val kind: ModelKind = ModelKind.STREAMING,",
    "    val sizeBytes: Long = 0L,",
    "    val assetId: Long = 0L,",
    "    val label: String? = null,",
    "    val rating: Int? = null,",
    "    val offered: Boolean = false,",
    "    val modelType: String? = null,",
    "    val files: ModelFiles? = null,",
    "    val limits: ModelLimits? = null,",
    "    val language: String? = null,",
    "    val isDefault: Boolean = false,",
    "    val notice: String? = null,",
    ") {",
    "    /** True when the engine can run this entry: it carries its model type,",
    "     *  files, limits and language and its (kind, modelType) pair is supported. */",
    "    val isSupported: Boolean",
    "        get() = modelType != null && files != null && limits != null &&",
    "            language != null &&",
    "            ModelRegistry.SUPPORTED_TYPES.contains(Pair(kind, modelType))",
    "}",
    "",
    "object ModelRegistry {",
]


def kotlin_constant(eid):
    return re.sub(r"(?<!^)([a-z])([A-Z])", r"\1_\2", eid).upper().replace("-", "_")


def kotlin_str(s):
    # Kotlin reads $ as a template start: a bare $ in a licence or a url owner
    # segment must reach the compiler as an escaped literal dollar.
    return ('"' + s.replace("\\", "\\\\").replace('"', '\\"')
            .replace("$", "\\$") + '"')


def _supported_types():
    pairs = ", ".join(f"ModelKind.{k.upper()} to {kotlin_str(t)}"
                      for k, t in model_types.SUPPORTED)
    return [f"    val SUPPORTED_TYPES: Set<Pair<ModelKind, String>> = setOf({pairs})",
            ""]


def render_kotlin(entries, keyword_entries=()):
    """The committed Kotlin, rendered from converted entries (speech first,
    then keyword models). Deterministic: same entries -> same bytes. `ALL` and
    `byId` name the speech entries only; `KEYWORD_MODELS` and `byKeywordId`
    the keyword entries only."""
    lines = list(HEADER)
    for e in list(entries) + list(keyword_entries):
        fam = "SHERPA_ONNX" if e["family"] == "sherpa-onnx" else "WHISPER"
        lines += [
            f"    val {kotlin_constant(e['id'])}: ModelEntry = ModelEntry(",
            f"        id = {kotlin_str(e['id'])},",
            f"        family = ModelFamily.{fam},",
            f"        url = {kotlin_str(e['url'])},",
            f"        sha256 = {kotlin_str(e['sha256'])},",
            f"        sizeMb = {e['size_mb']},",
            f"        licence = {kotlin_str(e['licence'])},",
            f"        hosted = {str(e['hosted']).lower()},",
            f"        archiveName = {kotlin_str(e['archive_name'])},",
            *mrf.render_fields(e, kotlin_str),
            "    )",
            "",
        ]
    names = ", ".join(kotlin_constant(e["id"]) for e in entries)
    kw_names = ", ".join(kotlin_constant(e["id"]) for e in keyword_entries)
    kw_list = f"listOf({kw_names})" if kw_names else "emptyList()"
    lines += [
        "    val ALL: List<ModelEntry> = listOf(" + names + ")",
        "",
        "    val KEYWORD_MODELS: List<ModelEntry> = " + kw_list,
        "",
        *_supported_types(),
        "    fun byId(id: String): ModelEntry? = ALL.firstOrNull { it.id == id }",
        "",
        "    fun byKeywordId(id: String): ModelEntry? = "
        "KEYWORD_MODELS.firstOrNull { it.id == id }",
        "}",
        "",
    ]
    return "\n".join(lines)
